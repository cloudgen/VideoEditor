def _window_table():
    """One map per code. A short row fails while this module loads."""
    table = {}
    for code, _name, _number in MenuLanguage.CODES:
        row = _WINDOW_ROWS.get(code)
        if row is None or len(row) != len(_WINDOW_KEYS):
            raise RuntimeError("window copy for {0} is incomplete".format(code))
        table[code] = dict(zip(_WINDOW_KEYS, row))
    return table


_WINDOW = _window_table()
